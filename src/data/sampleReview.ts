import type { DiffFile, DiffLine, ReviewData } from "../types";

const context = (
  id: string,
  oldLine: number,
  newLine: number,
  content: string,
  sectionIds: string[] = [],
): DiffLine => ({ id, type: "context", oldLine, newLine, content, sectionIds });

const addition = (
  id: string,
  newLine: number,
  content: string,
  sectionIds: string[],
  referenceIds: string[] = [],
): DiffLine => ({ id, type: "addition", newLine, content, sectionIds, referenceIds });

const deletion = (
  id: string,
  oldLine: number,
  content: string,
  sectionIds: string[],
  referenceIds: string[] = [],
): DiffLine => ({ id, type: "deletion", oldLine, content, sectionIds, referenceIds });

const hunk = (id: string, content: string): DiffLine => ({ id, type: "hunk", content });

